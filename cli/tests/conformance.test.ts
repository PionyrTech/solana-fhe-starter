/**
 * The committed vector file must match what the client produces today.
 *
 * `cargo test` verifies that Rust reproduces the operations in the file. This
 * verifies the other direction: that the file is not stale. Together they mean
 * the two implementations are pinned to each other.
 */

import { readFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { describe, expect, it } from "vitest";

import { serialize, toHex } from "../src/sdk/codec.js";
import { PARAM_SETS } from "../src/sdk/params.js";
import { DeterministicRandom } from "../src/sdk/random.js";
import { addCiphertexts, encrypt, keygen, scalarMulCiphertext } from "../src/sdk/rlwe.js";

const here = dirname(fileURLToPath(import.meta.url));
const vectorPath = resolve(
  join(here, "..", "..", "crates", "fhe-core", "tests", "vectors", "conformance.json"),
);

interface VectorCase {
  param_id: number;
  param_name: string;
  seed: string;
  slots_a: string[];
  slots_b: string[];
  scalar: string;
  a: string;
  b: string;
  sum: string;
  scaled: string;
}

describe("conformance vectors", () => {
  const document = JSON.parse(readFileSync(vectorPath, "utf8")) as { cases: VectorCase[] };

  it("is regenerated by the emitter, byte for byte", () => {
    // Reproduce the emitter's own choices. If this drifts, `npm run vectors`
    // and the committed file are out of step and Rust is testing stale bytes.
    const expectedSeeds = [0x0123456789abcdefn, 0xfedcba9876543210n];
    const expectedA = [
      [7n, 3n, 200n, 1n],
      [0n, 255n, 128n, 9n],
    ];
    const expectedB = [
      [10n, 4n, 50n, 0n],
      [1n, 1n, 127n, 9n],
    ];
    const expectedScalars = [5n, 300n];

    let cursor = 0;
    for (const params of PARAM_SETS) {
      for (let i = 0; i < expectedSeeds.length; i += 1) {
        const testCase = document.cases[cursor]!;
        const random = new DeterministicRandom(expectedSeeds[i]!);
        const secret = keygen(params, random);
        const a = encrypt(secret, expectedA[i]!, random);
        const b = encrypt(secret, expectedB[i]!, random);

        expect(testCase.param_name).toBe(params.name);
        expect(testCase.slots_a).toEqual(expectedA[i]!.map(String));
        expect(testCase.slots_b).toEqual(expectedB[i]!.map(String));

        expect(testCase.a).toBe(toHex(serialize(a.c0, a.c1)));
        expect(testCase.b).toBe(toHex(serialize(b.c0, b.c1)));

        const sum = addCiphertexts(a, b);
        expect(testCase.sum).toBe(toHex(serialize(sum.c0, sum.c1)));

        const scaled = scalarMulCiphertext(a, expectedScalars[i]!);
        expect(testCase.scaled).toBe(toHex(serialize(scaled.c0, scaled.c1)));

        cursor += 1;
      }
    }
    expect(cursor).toBe(document.cases.length);
  });
});
